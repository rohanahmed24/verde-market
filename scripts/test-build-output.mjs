import test from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { cpSync, existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, statSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, dirname, join, resolve } from "node:path";

const sourceScripts = import.meta.dirname;

function fixture(t) {
    const temporaryRoot = realpathSync(tmpdir());
    const temporary = mkdtempSync(join(temporaryRoot, "verde-build-output-"));
    const root = join(temporary, "site");
    const output = join(root, "dist");
    t.after(() => {
        const target = resolve(temporary);
        assert.equal(dirname(target), temporaryRoot, "Cleanup must remain in the OS temporary directory");
        assert(basename(target).startsWith("verde-build-output-"), "Cleanup must target this test's generated fixture");
        rmSync(target, { recursive: true, force: true });
    });
    for (const directory of ["scripts", "assets/css", "assets/js"]) mkdirSync(join(root, directory), { recursive: true });
    for (const file of ["build-site.mjs", "delivery-paths.mjs"]) cpSync(join(sourceScripts, file), join(root, "scripts", file));
    writeFileSync(join(root, "assets/css/verde-tailwind.css"), "body{color:green}");
    writeFileSync(join(root, "assets/js/fixture.js"), "window.fixture = 1;");
    writeFileSync(join(root, "index.html"), '<!doctype html><title>Build fixture</title><link rel="stylesheet" href="assets/css/verde-tailwind.css"><main>Fixture</main><script src="assets/js/fixture.js"></script>');
    writeFileSync(join(root, "robots.txt"), "User-agent: *\nAllow: /\n");
    writeFileSync(join(root, "sitemap.xml"), '<?xml version="1.0"?><urlset></urlset>');
    writeFileSync(join(root, "site.webmanifest"), '{"name":"Build fixture","icons":[]}');
    const build = () => spawnSync(process.execPath, [join(root, "scripts/build-site.mjs")], { cwd: root, encoding: "utf8", timeout: 10000 });
    return { root, output, temporary, build };
}

function expectBuilt(context) {
    const result = context.build();
    assert.equal(result.status, 0, result.stderr || result.error?.message || "Fixture build failed");
    assert(existsSync(join(context.output, ".verde-generated")));
    const manifest = JSON.parse(readFileSync(join(context.output, "asset-manifest.json"), "utf8"));
    const html = readFileSync(join(context.output, "index.html"), "utf8");
    for (const source of ["assets/css/verde-tailwind.css", "assets/js/fixture.js"]) {
        assert(manifest[source], `${source} must be fingerprinted`);
        assert(existsSync(join(context.output, manifest[source])));
        assert(html.includes(manifest[source]));
    }
    return manifest;
}

test("build output: a missing dist directory is created and populated", (t) => {
    expectBuilt(fixture(t));
});

test("build output: an empty precreated dist directory is reused without deleting it", (t) => {
    const context = fixture(t);
    mkdirSync(context.output);
    const original = statSync(context.output);
    expectBuilt(context);
    assert.equal(statSync(context.output).ino, original.ino, "The precreated output directory must be reused");
});

test("build output: a marked rebuild replaces stale generated files and asset hashes", (t) => {
    const context = fixture(t);
    const previous = expectBuilt(context);
    writeFileSync(join(context.output, "obsolete.txt"), "Generated by the previous fixture build");
    writeFileSync(join(context.root, "assets/js/fixture.js"), "window.fixture = 2;");
    const current = expectBuilt(context);
    assert.notEqual(current["assets/js/fixture.js"], previous["assets/js/fixture.js"]);
    assert.equal(existsSync(join(context.output, previous["assets/js/fixture.js"])), false);
    assert.equal(existsSync(join(context.output, "obsolete.txt")), false);
});

test("build output: an unmarked nonempty directory is refused and preserved", (t) => {
    const context = fixture(t);
    mkdirSync(context.output);
    const sentinel = join(context.output, "keep.txt");
    writeFileSync(sentinel, "Unrelated user content");
    const result = context.build();
    assert.notEqual(result.status, 0);
    assert.match(result.stderr, /marker|unmarked|non.?empty/i);
    assert.equal(readFileSync(sentinel, "utf8"), "Unrelated user content");
    assert.equal(existsSync(join(context.output, ".verde-generated")), false);
    assert.equal(existsSync(join(context.output, "index.html")), false);
});

test("build output: a regular file at dist is refused and preserved", (t) => {
    const context = fixture(t);
    writeFileSync(context.output, "Unrelated user file");
    assert.notEqual(context.build().status, 0);
    assert.equal(readFileSync(context.output, "utf8"), "Unrelated user file");
});

test("build output: a linked output directory is refused even if its target has a build marker", (t) => {
    const context = fixture(t);
    const target = join(context.temporary, "unrelated-target");
    mkdirSync(target);
    writeFileSync(join(target, ".verde-generated"), "Generated by scripts/build-site.mjs.\n");
    writeFileSync(join(target, "keep.txt"), "Linked target content");
    try {
        symlinkSync(target, context.output, process.platform === "win32" ? "junction" : "dir");
    } catch (error) {
        if (["EPERM", "EACCES", "ENOSYS"].includes(error.code)) {
            t.skip(`Directory links unavailable: ${error.code}`);
            return;
        }
        throw error;
    }
    const result = context.build();
    assert.notEqual(result.status, 0, "A marker in a linked target must not authorize replacing the output link");
    assert(lstatSync(context.output).isSymbolicLink());
    assert.equal(readFileSync(join(target, "keep.txt"), "utf8"), "Linked target content");
    assert.equal(existsSync(join(target, "index.html")), false);
});
